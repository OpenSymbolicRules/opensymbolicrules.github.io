#!/usr/bin/env python3
"""Publish committed Markdown from mathematical-domain repositories."""

import json
import hashlib
import posixpath
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
from urllib.parse import quote, urlsplit

EMERGING = ('LinearAlgebra', 'TensorAlgebra', 'DifferentialGeometry')
DOMAINS = ('Integration', 'Calculus', 'Algebra', 'Trigonometry', 'Logic', *EMERGING)
MARKER = '.osr-domain-docs-generated'
LINK = re.compile(r'(!?\[[^\[\]]*\]\()([^\s()]+)(\))')


def git(repo, *args):
    return subprocess.check_output(['git', '-C', str(repo), *args], text=True).strip()


def rewrite_links(text, repo, commit, path):
    """Point repository-relative Markdown links at the exact source revision."""
    def replace(match):
        target = match.group(2)
        parts = urlsplit(target)
        if parts.scheme or parts.netloc or target.startswith('/'):
            return match.group(0)
        relative = posixpath.normpath(posixpath.join(posixpath.dirname(path), parts.path))
        if relative == '..' or relative.startswith('../'):
            raise ValueError(f'link escapes repository: {path}: {target}')
        if not parts.path:
            relative = path
        raw = match.group(1).startswith('!')
        base = ('https://raw.githubusercontent.com/' if raw else 'https://github.com/')
        prefix = f'{base}OpenSymbolicRules/{repo}/'
        prefix += f'{commit}/' if raw else f'blob/{commit}/'
        url = prefix + quote(relative, safe='/')
        if parts.query:
            url += '?' + parts.query
        if parts.fragment:
            url += '#' + parts.fragment
        return match.group(1) + url + match.group(3)
    # Do not execute shortcode syntax found in imported repository text.
    return LINK.sub(replace, text).replace('{{<', '&#123;{<').replace('{{%', '&#123;{%')


def collect(source, destination):
    source, destination = Path(source), Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    # Preflight every destination before replacing any generated directory.
    for repo in DOMAINS:
        folder = destination / repo.lower() / 'documentation'
        if folder.exists() and not (folder / MARKER).is_file():
            raise ValueError(f'refusing to replace non-generated directory: {folder}')
    for repo in DOMAINS:
        folder = destination / repo.lower() / 'documentation'
        if folder.exists():
            shutil.rmtree(folder)
        folder.mkdir(parents=True)
        (folder / MARKER).write_text('Generated by scripts/collect_domain_docs.py\n')
        checkout = source / repo
        index = f'---\ntitle: Documentation\n---\n\n# {repo} documentation\n\n'
        if not (checkout / '.git').exists():
            index += (f'Documentation is not yet available from the '
                      f'[{repo} repository](https://github.com/OpenSymbolicRules/{repo}).\n')
            (folder / '_index.md').write_text(index, encoding='utf-8')
            continue
        commit = git(checkout, 'rev-parse', '--verify', 'HEAD')
        entries = subprocess.check_output(
            ['git', '-C', str(checkout), 'ls-tree', '-r', '-z', commit, '--', 'README.md', 'docs'],
        ).split(b'\0')
        files = []
        for entry in entries:
            if not entry:
                continue
            meta, name = entry.split(b'\t', 1)
            mode, kind, _ = meta.decode('ascii').split()
            path = name.decode('utf-8')
            if mode not in ('100644', '100755') or kind != 'blob' or not path.lower().endswith('.md'):
                continue
            files.append(path)
        index += f'Source: [{repo} at `{commit[:12]}`](https://github.com/OpenSymbolicRules/{repo}/tree/{commit}).\n\n'
        if not files:
            index += 'Documentation is not yet available in this revision.\n'
        for path in sorted(files):
            # A stable lowercase route avoids Hugo case-folding and index-name
            # collisions, while the original path remains visible in the page.
            stem = 'doc-' + hashlib.sha256(path.encode('utf-8')).hexdigest()
            relative = PurePosixPath(stem + '.md')
            output = folder / 'pages' / relative
            output.parent.mkdir(parents=True, exist_ok=True)
            text = subprocess.check_output(['git', '-C', str(checkout), 'show', f'{commit}:{path}']).decode('utf-8')
            title = path
            front = f'---\ntitle: {json.dumps(title)}\n---\n\n'
            attribution = (f'Source: [{repo}/{path} at `{commit[:12]}`]'
                           f'(https://github.com/OpenSymbolicRules/{repo}/blob/{commit}/{quote(path, safe="/")}).\n\n')
            output.write_text(front + attribution + rewrite_links(text, repo, commit, path), encoding='utf-8')
            route = str(PurePosixPath('pages') / relative.with_suffix('')) + '/'
            index += f'- [{path}]({route})\n'
        (folder / '_index.md').write_text(index, encoding='utf-8')


if __name__ == '__main__':
    collect(sys.argv[1] if len(sys.argv) > 1 else '.sources',
            sys.argv[2] if len(sys.argv) > 2 else 'content/domains')
